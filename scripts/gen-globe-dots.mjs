// Build-time generator for the hero dot-globe.
//
// Reads the low-res (110m) land geometry from world-atlas, samples a roughly
// equal-area lat/lng grid, keeps the points that fall on land, and bakes them
// into `src/components/hero/globe-dots.ts` as a flat, precomputed array.
//
// This moves ALL geography work to dev time: the runtime ships a tiny number
// array — no topojson parse, no triangulation, no 3D libraries.
//
//   node scripts/gen-globe-dots.mjs
//
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topoPath = require.resolve("world-atlas/land-110m.json");
const topo = JSON.parse(readFileSync(topoPath, "utf8"));
const land = feature(topo, topo.objects.land);

// Polygons as [outerRing, ...holes][] of [lng, lat] pairs.
const polygons = [];
for (const geom of land.features ?? [land]) {
  const g = geom.geometry ?? geom;
  if (g.type === "Polygon") polygons.push(g.coordinates);
  else if (g.type === "MultiPolygon") for (const p of g.coordinates) polygons.push(p);
}

function pointInRing(lng, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const xi = ring[i][0], yi = ring[i][1];
    const xj = ring[j][0], yj = ring[j][1];
    const hit = yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
    if (hit) inside = !inside;
  }
  return inside;
}

function isLand(lng, lat) {
  for (const poly of polygons) {
    if (!pointInRing(lng, lat, poly[0])) continue;
    let inHole = false;
    for (let h = 1; h < poly.length; h++) {
      if (pointInRing(lng, lat, poly[h])) { inHole = true; break; }
    }
    if (!inHole) return true;
  }
  return false;
}

// Equal-ish-area sampling: step longitude wider near the poles (÷cosφ) so the
// projected dots read as an even grid on the sphere rather than crowding up top.
const LAT_STEP = 2.6;
const BASE_LNG_STEP = 2.6;
const LAT_MIN = -56; // trim Antarctica fringe; keeps the populated world
const LAT_MAX = 78;

const dots = [];
for (let lat = LAT_MIN; lat <= LAT_MAX; lat += LAT_STEP) {
  const lngStep = Math.min(18, BASE_LNG_STEP / Math.max(0.18, Math.cos((lat * Math.PI) / 180)));
  for (let lng = -180; lng < 180; lng += lngStep) {
    if (isLand(lng, lat)) dots.push([+lat.toFixed(2), +lng.toFixed(2)]);
  }
}

// Bright metro highlights (lat, lng) — drives the city-light glow + arc hubs.
const CITIES = [
  [40.7, -74], [34, -118], [19.4, -99.1], [-23.5, -46.6], [-34.6, -58.4],
  [51.5, -0.1], [48.9, 2.35], [40.4, -3.7], [52.5, 13.4], [55.7, 37.6], [41, 28.9],
  [6.5, 3.4], [30, 31.2], [-26.2, 28], [-1.3, 36.8],
  [25, 55], [19, 72.8], [28.6, 77.2], [1.3, 103.8], [35.7, 139.7], [31.2, 121.5],
  [39.9, 116.4], [37.6, 127], [-6.2, 106.8], [22.3, 114.2], [-33.9, 151],
];

const flat = dots.flat();
const out = `// AUTO-GENERATED by scripts/gen-globe-dots.mjs — do not edit by hand.
// Precomputed land-dot coordinates for the hero globe (110m land, ${dots.length} points).
// Flat [lat, lng, lat, lng, ...] so it parses as one small numeric literal.
export const LAND_DOTS: readonly number[] = [${flat.join(",")}];
export const CITY_DOTS: readonly [number, number][] = ${JSON.stringify(CITIES)};
`;

const target = new URL("../src/components/hero/globe-dots.ts", import.meta.url);
writeFileSync(target, out);
console.log(`Wrote ${dots.length} land dots + ${CITIES.length} cities (${(out.length / 1024).toFixed(1)} KB) → src/components/hero/globe-dots.ts`);
